def main_menu():

    while True:
        clear_screen()

        print("=" * 55)
        print("║" + " ГЛАВНОЕ МЕНЮ ЛАБОРАТОРНОЙ РАБОТЫ ".center(53) + "║")
        print("=" * 55)

        print("  [1] Задание №2  (Площадь и периметр прямоугольника)")
        print("  [2] Задание №10 (Разбор четырехзначного числа)")
        print("  [3] Задание №19 (Прямоугольный треугольник)")
        print("  [0] Выход из программы")

        print("=" * 55)

        choice = input("  ► Выберите номер пункта меню: ").strip()

        if choice == '1':
            task_2()

        elif choice == '2':
            task_10()

        elif choice == '3':
            task_19()

        elif choice == '0':
            clear_screen()
            print("\n  Программа успешно завершена. Всего доброго!\n")
            sys.exit()

        else:
            print("\n  [!] Неверный пункт меню.")

        input("\n  Нажмите Enter для возврата в меню...")


# =========================================================
# ЗАПУСК ПРОГРАММЫ
# =========================================================

if __name__ == "__main__":
    main_menu()
