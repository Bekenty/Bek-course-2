def task_19():
    clear_screen()
    print_header("ЗАДАНИЕ №19: ПРЯМОУГОЛЬНЫЙ ТРЕУГОЛЬНИК")

    try:
        a = float(input("  ► Введите первый катет: "))
        b = float(input("  ► Введите второй катет: "))

        if a <= 0 or b <= 0:
            print("\n  [!] Ошибка: катеты должны быть больше нуля!")
            return

        # Гипотенуза
        c = math.sqrt(a ** 2 + b ** 2)

        # Площадь
        S = (a * b) / 2

        # Периметр
        P = a + b + c

        # Острые углы
        angle_a = math.degrees(math.atan(a / b))
        angle_b = math.degrees(math.atan(b / a))

        print("\n" + "-" * 55)
        print("  ✔ Результаты вычислений:")
        print(f"    • Гипотенуза : {c:,.2f}")
        print(f"    • Площадь    : {S:,.2f}")
        print(f"    • Периметр   : {P:,.2f}")
        print(f"    • Угол 1     : {angle_a:,.2f}°")
        print(f"    • Угол 2     : {angle_b:,.2f}°")
        print("-" * 55)

    except ValueError:
        print("\n  [!] Ошибка: пожалуйста, вводите только числа.")


