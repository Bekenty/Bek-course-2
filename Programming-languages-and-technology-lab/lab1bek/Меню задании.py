import os
import sys
import math


def clear_screen():
    """Очистка консоли"""
    os.system('cls' if os.name == 'nt' else 'clear')


def print_header(title):
    """Красивая рамка для заголовков"""
    print("\n" + "=" * 55)
    print(f"║ {title.center(51)} ║")
    print("=" * 55)


# =========================================================
# ЗАДАНИЕ №2
# =========================================================

def task_2():
    clear_screen()
    print_header("ЗАДАНИЕ №2: РАСЧЕТ ПРЯМОУГОЛЬНИКА")

    try:
        a = float(input("  ► Введите длину прямоугольника: "))
        b = float(input("  ► Введите ширину прямоугольника: "))

        if a <= 0 or b <= 0:
            print("\n  [!] Ошибка: стороны должны быть больше нуля!")
            return

        S = a * b
        P = 2 * (a + b)

        print("\n" + "-" * 55)
        print("  ✔ Результаты вычислений:")
        print(f"    • Площадь (S) : {S:,.2f}")
        print(f"    • Периметр (P): {P:,.2f}")
        print("-" * 55)

    except ValueError:
        print("\n  [!] Ошибка: пожалуйста, вводите только числа.")


