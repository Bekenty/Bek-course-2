# Ввод данных по банковскому вкладу
principal = float(input("Введите сумму банковского вклада: "))
rate = float(input("Введите годовую процентную ставку (в %): "))
years = float(input("Введите срок вклада (в годах): "))

# Вычисление итоговой суммы по формуле сложных процентов:
# A = P * (1 + r / 100) ** t
final_amount = principal * (1 + rate / 100) ** years

# Вывод результатов (округляем сумму до 2 знаков после запятой для красоты)
print("\n--- Результаты расчёта ---")
print(f"Сумма вклада: {principal}")
print(f"Годовая ставка: {rate}%")
print(f"Срок: {years} лет")
print(f"Итоговая сумма на счете: {final_amount:.2f}")